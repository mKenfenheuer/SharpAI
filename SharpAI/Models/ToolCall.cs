using System.Text.Json.Serialization;

namespace SharpAI.Models
{
    /// <summary>
    /// Represents a tool call made by the AI model during chat completion.
    /// Compatible with OpenAI's tool call format.
    /// </summary>
    public class ToolCall
    {
        /// <summary>
        /// The type of tool being called (currently only "function" is supported).
        /// </summary>
        [JsonPropertyName("type")]
        public required ToolType Type { get; set; }

        /// <summary>
        /// The function that the model called (when type is "function").
        /// </summary>
        [JsonPropertyName("function")]
        public FunctionCall? Function { get; set; }

        /// <summary>
        /// A unique identifier for the tool call (used for streaming compatibility).
        /// </summary>
        [JsonPropertyName("id")]
        public string? CallId { get; set; }
    }

    /// <summary>
    /// Represents a function call with its name, namespace, and arguments.
    /// </summary>
    public class FunctionCall
    {
        /// <summary>
        /// The name of the function to call.
        /// </summary>
        [JsonPropertyName("name")]
        public required string Name { get; set; }

        /// <summary>
        /// The namespace of the function (default: "functions").
        /// </summary>
        [JsonIgnore]
        public string Namespace { get; set; } = "functions"; // Default namespace

        /// <summary>
        /// The arguments to call the function with, as generated by the model in JSON format.
        /// </summary>
        [JsonPropertyName("arguments")]
        public required string Arguments { get; set; } // JSON string
    }

    /// <summary>
    /// Defines the type of tool that can be called.
    /// </summary>
    [JsonConverter(typeof(LowercaseEnumConverter<ToolType>))]
    public enum ToolType 
    { 
        /// <summary>
        /// Function tool type for calling external functions.
        /// </summary>
        Function 
    }
}