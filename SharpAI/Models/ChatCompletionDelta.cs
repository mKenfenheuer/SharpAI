using System.Text.Json.Serialization;

namespace SharpAI.Models
{
    /// <summary>
    /// Represents a delta (partial update) in a streaming chat completion response.
    /// 
    /// <para><strong>OpenAI Compatibility:</strong></para>
    /// <para>Fully compatible with OpenAI's streaming chat completion delta format.</para>
    /// <para>Standard fields: role, content, refusal, tool_calls</para>
    /// 
    /// <para><strong>Extensions:</strong></para>
    /// <para>• <c>reasoning</c>: Streaming delta for chain-of-thought reasoning (SharpAI extension)</para>
    /// <para>• <c>commentary</c>: Streaming delta for meta-commentary (SharpAI extension)</para>
    /// 
    /// <para><strong>Usage:</strong></para>
    /// <para>Used in Server-Sent Events for real-time streaming. Extended fields provide transparency into model's thinking process.</para>
    /// </summary>
    public class ChatCompletionDelta
    {
        /// <summary>
        /// The role of the message author. Usually only present in the first delta.
        /// </summary>
        [JsonPropertyName("role")]
        public ChatRole? Role { get; set; }

        /// <summary>
        /// The content delta/chunk being streamed.
        /// </summary>
        [JsonPropertyName("content")]
        public string? Content { get; set; }

        /// <summary>
        /// The refusal delta. Present when the model refuses to fulfill the request.
        /// </summary>
        [JsonPropertyName("refusal")]
        public string? Refusal { get; set; }

        /// <summary>
        /// Tool call deltas generated by the model, such as function calls.
        /// </summary>
        [JsonPropertyName("tool_calls")]
        public List<ToolCallDelta>? ToolCalls { get; set; }

        /// <summary>
        /// The reasoning delta/chunk being streamed. Used by reasoning models for chain-of-thought.
        /// 
        /// <para><strong>SharpAI Extension:</strong></para>
        /// <para>This field is not part of the standard OpenAI streaming API.</para>
        /// <para>Contains streaming chunks of analysis/reasoning content from Harmony analysis channel.</para>
        /// <para>Enables real-time visibility into model's reasoning process.</para>
        /// </summary>
        [JsonPropertyName("reasoning")]
        public string? Reasoning { get; set; }

        /// <summary>
        /// The commentary delta/chunk being streamed. Used for meta-commentary about the response process.
        /// 
        /// <para><strong>SharpAI Extension:</strong></para>
        /// <para>This field is not part of the standard OpenAI streaming API.</para>
        /// <para>Contains streaming chunks of meta-commentary from Harmony commentary channel.</para>
        /// <para>Provides insights into model's thinking and decision-making process.</para>
        /// </summary>
        [JsonPropertyName("commentary")]
        public string? Commentary { get; set; }
    }

    /// <summary>
    /// Represents a delta (partial update) for a tool call in streaming responses.
    /// </summary>
    public class ToolCallDelta
    {
        /// <summary>
        /// The index of this tool call in the list.
        /// </summary>
        [JsonPropertyName("index")]
        public int Index { get; set; }

        /// <summary>
        /// The ID of the tool call. Usually only present in the first delta for this tool call.
        /// </summary>
        [JsonPropertyName("id")]
        public string? Id { get; set; }

        /// <summary>
        /// The type of the tool. Usually only present in the first delta for this tool call.
        /// </summary>
        [JsonPropertyName("type")]
        public string? Type { get; set; }

        /// <summary>
        /// Function call delta information.
        /// </summary>
        [JsonPropertyName("function")]
        public FunctionCallDelta? Function { get; set; }
    }

    /// <summary>
    /// Represents a delta (partial update) for a function call in streaming responses.
    /// </summary>
    public class FunctionCallDelta
    {
        /// <summary>
        /// The name of the function. Usually only present in the first delta for this function call.
        /// </summary>
        [JsonPropertyName("name")]
        public string? Name { get; set; }

        /// <summary>
        /// The arguments delta/chunk being streamed for the function call.
        /// </summary>
        [JsonPropertyName("arguments")]
        public string? Arguments { get; set; }
    }

    /// <summary>
    /// Represents a streaming choice in a chat completion response with delta updates.
    /// </summary>
    public class ChatCompletionStreamingChoice
    {
        /// <summary>
        /// The index of this choice in the list of choices.
        /// </summary>
        [JsonPropertyName("index")]
        public int Index { get; set; }

        /// <summary>
        /// The delta (partial update) for this choice.
        /// </summary>
        [JsonPropertyName("delta")]
        public ChatCompletionDelta? Delta { get; set; }

        /// <summary>
        /// The reason the model stopped generating tokens (stop, length, content_filter, tool_calls, etc.).
        /// Usually null until the final chunk.
        /// </summary>
        [JsonPropertyName("finish_reason")]
        public string? FinishReason { get; set; }

        /// <summary>
        /// Log probability information for the choice (if requested).
        /// </summary>
        [JsonPropertyName("logprobs")]
        public object? LogProbs { get; set; }
    }
}