using System.Text.Json.Serialization;

namespace SharpAI.Models
{
    /// <summary>
    /// Represents a single message in a chat conversation.
    /// Compatible with OpenAI's chat message format.
    /// </summary>
    public class ChatMessage
    {
        /// <summary>
        /// The role of the message author (system, user, assistant, or tool).
        /// </summary>
        [JsonPropertyName("role")]
        public required ChatRole Role { get; set; }

        /// <summary>
        /// The content of the message. Can be text, or an array of content parts for multi-modal inputs.
        /// </summary>
        [JsonPropertyName("content")]
        public string? Content { get; set; } // string | array (text, image, audio, etc.)

        /// <summary>
        /// An optional name for the participant. Provides the model information to differentiate between participants of the same role.
        /// </summary>
        [JsonPropertyName("name")]
        public string? Name { get; set; }

        /// <summary>
        /// Tool call that this message is responding to. Required if role is 'tool'.
        /// </summary>
        [JsonPropertyName("tool_call_id")]
        public string? ToolCallId { get; set; }

        /// <summary>
        /// The tool calls generated by the model, such as function calls. Present when the model calls a tool.
        /// </summary>
        [JsonPropertyName("tool_calls")]
        public List<ToolCall>? ToolCalls { get; set; }
    }

    /// <summary>
    /// Defines the role of a chat message participant.
    /// </summary>
    [JsonConverter(typeof(LowercaseEnumConverter<ChatRole>))]
    public enum ChatRole 
    { 
        /// <summary>
        /// System message that sets the behavior of the assistant.
        /// </summary>
        System, 
        /// <summary>
        /// User message containing the user's input or question.
        /// </summary>
        User, 
        /// <summary>
        /// Assistant message containing the AI's response.
        /// </summary>
        Assistant, 
        /// <summary>
        /// Tool message containing the result of a tool call.
        /// </summary>
        Tool 
    }
}
